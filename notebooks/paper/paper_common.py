_READ: dict[str, str] = {}


def path(rel: str) -> Path:
    """Absolute path of an input file, recording its SHA-256 for the provenance listing."""
    p = DATA_ROOT / rel
    if not p.exists():
        raise FileNotFoundError(f"{p} not found; set CSF_GRAPHS_DIR to the CSF-graphs archive root")
    _READ[rel] = hashlib.sha256(p.read_bytes()).hexdigest()
    return p


def read_csv(rel: str) -> pd.DataFrame:
    return pd.read_csv(path(rel))


def read_summary(key: str) -> dict:
    """Per-model summary written by the experiment renderer (CounterFact scores, detection, unedited control)."""
    return json.loads(path(f"existing-renderer/classic-gram/{key}/summary.json").read_text())


def inputs_used() -> pd.DataFrame:
    """Files read so far, with their SHA-256 digests."""
    return pd.DataFrame(sorted(_READ.items()), columns=["file", "sha256"])


def base_model_results() -> pd.DataFrame:
    """One row per base model with everything Tables 2 and 3 need.

    ES, PS, NS  mean efficacy, paraphrase and neighborhood scores over the 1,000 edits (in percent)
    S           harmonic mean of ES, PS and NS
    target      edited layer l* (0-indexed); L number of layers
    exact       edits for which the detector returns l*; n evaluated edits
    detected    histogram {layer: number of edits for which the detector returned that layer}
    l0          layer the detector selects on the unedited checkpoint (control)
    s_target_edited / s_target_control   detector score at l*, mean over edited checkpoints / unedited
    s_l0_control                          detector score of the unedited checkpoint at its own peak l0
    """
    fam = read_csv("data/classic-family-summary.csv").set_index("model")
    prof = read_csv("data/classic-layer-profile-statistics.csv")
    rows = []
    for m in MODELS.itertuples():
        s = read_summary(m.key)
        res = s["models"][m.key]
        loc = s["baseline_controls"][m.key]["localization"]
        target = int(fam.loc[m.key, "target_layer"])
        l0 = int(loc["selected_layer"])
        assert l0 == int(fam.loc[m.key, "baseline_selected_layer"])
        p = prof[prof.model == m.key].set_index("layer")
        es, ps, ns = (100 * res[k] for k in ("mean_efficacy_score", "mean_paraphrase_score", "mean_neighborhood_score"))
        rows.append(
            dict(
                key=m.key, name=m.name, family=m.family, period=m.period,
                target=target, L=len(loc["eligible_layers"]) + len(loc["excluded_layers"]),
                ES=es, PS=ps, NS=ns, S=3 / (1 / es + 1 / ps + 1 / ns),
                n=int(res["evaluated"]), rome_success=int(res["rome_success_count"]), exact=int(res["exact_count"]),
                detected={int(k): int(v) for k, v in res["detected_layers"].items()},
                l0=l0,
                s_target_edited=float(p.loc[target, "edited_mean"]),
                s_target_control=float(p.loc[target, "baseline_score"]),
                s_l0_control=float(p.loc[l0, "baseline_score"]),
            )
        )
    df = pd.DataFrame(rows)
    df["exact_pct"] = 100 * df.exact / df.n
    df["mae"] = [sum(abs(layer - t) * c for layer, c in d.items()) / n for d, t, n in zip(df.detected, df.target, df.n)]
    df["lift"] = df.s_target_edited / df.s_target_control
    df["control_flags"] = df.l0 == df.target
    return df


class Checks:
    """Collects comparisons between a computed value and the value printed in the paper."""

    def __init__(self):
        self.rows = []

    def value(self, claim, where, computed, paper, tol=0.0):
        """Numeric comparison within an absolute tolerance (tol=0 means exact)."""
        ok = abs(float(computed) - float(paper)) <= tol + 1e-12
        self.rows.append(dict(claim=claim, where=where, computed=computed, paper=paper, ok=ok))
        return ok

    def printed(self, claim, where, computed, paper: str, decimals=1):
        """Compare a number after rounding it the way the paper prints it, e.g. 80.1 or 2.48."""
        text = f"{computed:.{decimals}f}"
        self.rows.append(dict(claim=claim, where=where, computed=text, paper=paper, ok=text == paper))

    def same(self, claim, where, computed, paper):
        """Exact equality of any two values (sets, lists, booleans, strings)."""
        self.rows.append(dict(claim=claim, where=where, computed=computed, paper=paper, ok=computed == paper))

    def table(self) -> pd.DataFrame:
        return pd.DataFrame(self.rows)

    def assert_all(self):
        bad = [r for r in self.rows if not r["ok"]]
        if bad:
            raise AssertionError(f"{len(bad)} of {len(self.rows)} checks differ from the paper:\n" + pd.DataFrame(bad).to_string())
        print(f"All {len(self.rows)} checks match the paper.")


def latex_rows_equal(generated: str, paper: str) -> bool:
    """Compare LaTeX table rows while ignoring alignment whitespace."""
    norm = lambda s: [" ".join(line.split()) for line in s.strip().splitlines() if line.strip()]
    return norm(generated) == norm(paper)


def diff_rows(generated: str, paper: str) -> pd.DataFrame:
    """Rows that differ between the generated LaTeX and the paper (empty when they agree)."""
    from itertools import zip_longest

    norm = lambda s: [" ".join(line.split()) for line in s.strip().splitlines() if line.strip()]
    pairs = [(g, p) for g, p in zip_longest(norm(generated), norm(paper), fillvalue="") if g != p]
    return pd.DataFrame(pairs, columns=["generated", "paper"])
