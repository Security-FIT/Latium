"""Paid adaptive corrections and competing predictive codes for GRAM MDL v2.

The source is the same FP32/lattice representation as v1. Multiple views are
encoded sequentially; a later view may condition on the ordinary Gram. This
is a joint prefix description, with no independence claim between views.
"""

from __future__ import annotations

from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass
import math

import numpy as np
import torch

from src.structural.detectors.gram_mdl_codec import GramCodec, GramCorrection, integer_code, universal_bits


CODEC_VERSION = "gram-adaptive-rice-fp32-v2"
PRECISIONS = (8, 12, 16, 24, 32, 53, 64)
BACKGROUNDS = ("direct", "constant-depth", "affine-depth", "quadratic-depth", "adaptive-depth")


def index_bits(count: int) -> int:
    if count < 1:
        raise ValueError("A code family cannot be empty")
    return (count - 1).bit_length()


def quantized_parameter(values: np.ndarray, precision: int) -> tuple[np.ndarray, int]:
    """A paid shared-exponent dyadic vector, or literal FP64 escape words."""
    vector = np.asarray(values, dtype=np.float64).reshape(-1)
    if not vector.size or not np.isfinite(vector).all() or precision not in PRECISIONS:
        raise ValueError("Invalid finite correction parameter or precision")
    if precision == 64:
        return vector.copy(), 64 * int(vector.size)
    largest = float(np.max(np.abs(vector)))
    exponent = math.frexp(largest)[1] if largest else 0
    # ldexp handles very small finite parameters without a log/exp round trip.
    shift = exponent - precision + 1
    scaled = np.ldexp(vector, -shift)
    if not np.isfinite(scaled).all():
        raise ValueError("Correction cannot be represented by this dyadic format")
    words = np.rint(scaled).astype(np.int64)
    restored = np.ldexp(words.astype(np.float64), shift)
    signed_exponent = 2 * shift if shift >= 0 else -2 * shift - 1
    return restored, universal_bits(signed_exponent) + integer_code(words).bits


@dataclass(frozen=True)
class AdaptiveCorrection:
    precision: int
    parameter_bits: int
    reconstruction_bits: int
    views: Mapping[str, GramCorrection]
    parameter_blocks: Mapping[str, int]

    @property
    def bits(self) -> int:
        return self.parameter_bits + self.reconstruction_bits

    def record(self) -> dict:
        return {
            "precision": self.precision,
            "precision_bits": index_bits(len(PRECISIONS)),
            "parameter_bits": self.parameter_bits,
            "parameter_blocks": dict(self.parameter_blocks),
            "reconstruction_bits": self.reconstruction_bits,
            "views": {
                name: {"remaining_energy_scale": item.scale, "reconstruction_bits": item.reconstruction_bits}
                for name, item in self.views.items()
            },
        }


def describe_adaptive_corrections(
    current: Mapping[str, torch.Tensor],
    direction: torch.Tensor,
    mixer: torch.Tensor,
    codec: GramCodec,
    *,
    originals: Mapping[str, np.ndarray] | None = None,
) -> tuple[AdaptiveCorrection, list[dict]]:
    """Encode one physical left peel across all views, paying shared u once.

    A_v = c_v B_v + u g_v.T + g_v u.T - gamma_v u u.T. All moments and
    baselines are generated by the SAME (u,z); no per-view peel is fitted.
    Quantization error restores each original lattice exactly.
    """
    device = next(iter(current.values())).device
    u = direction.detach().to(device=device, dtype=torch.float64)
    z = mixer.detach().to(device=device, dtype=torch.float64)
    u = u / torch.linalg.vector_norm(u)
    original_lattices = dict(originals) if originals is not None else {}
    baselines, moments, scalars = {}, {}, {}
    for name, source in current.items():
        gram = source.to(device=device, dtype=torch.float64)
        moment = gram @ z
        gamma = float(z @ moment)
        peeled = gram - torch.outer(u, moment) - torch.outer(moment, u) + gamma * torch.outer(u, u)
        scale = float(torch.trace(peeled))
        if not math.isfinite(scale) or scale <= 0:
            raise ValueError("Shared correction has nonpositive remaining energy")
        if name not in original_lattices:
            original_lattices[name] = codec.quantize(source)
        baselines[name] = codec.quantize(peeled / scale)
        moments[name] = moment.cpu().numpy()
        scalars[name] = np.asarray([gamma, scale])
    descriptions = []
    records = []
    for precision in PRECISIONS:
        uq, paid = quantized_parameter(u.cpu().numpy(), precision)
        parameter_blocks = {"direction": paid}
        paid += index_bits(len(PRECISIONS))
        views = {}
        for name in current:
            gq, g_bits = quantized_parameter(moments[name], precision)
            sq, s_bits = quantized_parameter(scalars[name], precision)
            paid += g_bits + s_bits
            parameter_blocks[f"{name}.moment"] = g_bits
            parameter_blocks[f"{name}.scalars"] = s_bits
            provisional = GramCorrection(
                uq, gq, float(sq[0]), float(sq[1]), baselines[name], np.zeros(codec.entries, dtype=np.int64)
            )
            errors = original_lattices[name] - provisional.prediction(codec)
            views[name] = GramCorrection(uq, gq, float(sq[0]), float(sq[1]), baselines[name], errors)
        result = AdaptiveCorrection(
            precision, paid, sum(item.reconstruction_bits for item in views.values()), views, parameter_blocks
        )
        descriptions.append(result)
        records.append(result.record())
    return min(descriptions, key=lambda item: (item.bits, item.precision)), records


@dataclass(frozen=True)
class BackgroundDescription:
    model: str
    model_bits: int
    blocks: Mapping[str, Sequence[int]]

    @property
    def bits(self) -> int:
        return self.model_bits + sum(sum(blocks) for blocks in self.blocks.values())

    def record(self) -> dict:
        return {
            "model": self.model,
            "model_bits": self.model_bits,
            "bits": self.bits,
            "blocks": {name: list(values) for name, values in self.blocks.items()},
        }


class BackgroundFamily:
    """Constant, affine, curved drift and paid stage resets, with bounded cache.

    ``at(view, position)`` supplies an integer source vector. Views are decoded
    in the given order. Predictor choices and the background identifier are
    paid under both hypotheses. A replacement can affect at most four blocks
    in each view, including the conditional current-layer predictor.
    """

    def __init__(
        self,
        at: Callable[[str, int], np.ndarray],
        views: Sequence[str],
        count: int,
        on_position: Callable[[int], None] | None = None,
    ) -> None:
        self.at = at
        self.views = tuple(views)
        self.count = count
        self._cost_cache: dict[tuple[str, int], dict[str, int]] = {}
        blocks = {model: {view: [] for view in self.views} for model in BACKGROUNDS}
        for pos in range(count):
            for view in self.views:
                for model in BACKGROUNDS:
                    blocks[model][view].append(self.block(model, view, pos))
            if on_position is not None:
                on_position(pos)
        self.baseline = {
            model: BackgroundDescription(model, index_bits(len(BACKGROUNDS)), blocks[model]) for model in BACKGROUNDS
        }

    def block(
        self, model: str, view: str, pos: int, replacements: Mapping[str, tuple[int, np.ndarray]] | None = None
    ) -> int:
        def at(name: str, index: int) -> np.ndarray:
            replacement = (replacements or {}).get(name)
            return replacement[1] if replacement is not None and index == replacement[0] else self.at(name, index)

        conditional = view != self.views[0]
        key = (view, pos)
        costs = self._cost_cache.get(key)
        if costs is None:
            value = at(view, pos)
            costs = {"direct": integer_code(value).bits}
            if pos >= 1:
                costs["constant-depth"] = integer_code(value - at(view, pos - 1)).bits
            if pos >= 2:
                costs["affine-depth"] = integer_code(value - 2 * at(view, pos - 1) + at(view, pos - 2)).bits
            if pos >= 3:
                prediction = 3 * at(view, pos - 1) - 3 * at(view, pos - 2) + at(view, pos - 3)
                costs["quadratic-depth"] = integer_code(value - prediction).bits
            if conditional:
                costs["ordinary-current"] = integer_code(value - at(self.views[0], pos)).bits
            if len(self._cost_cache) >= 8:
                self._cost_cache.pop(next(iter(self._cost_cache)))
            self._cost_cache[key] = costs
        if model == "adaptive-depth":
            # Reset, three causal depth predictors and optional ordinary view.
            return index_bits(5 if conditional else 4) + min(costs.values())
        if model == "direct":
            return costs["direct"]
        choices = [costs["direct"]]
        if model in costs:
            choices.append(costs[model])
        if conditional:
            choices.append(costs["ordinary-current"])
        # Fixed-size mode alphabet also covers startup blocks.
        return index_bits(3 if conditional else 2) + min(choices)

    def replaced(self, position: int, baselines: Mapping[str, np.ndarray]) -> dict[str, int]:
        replacements = {view: (position, value) for view, value in baselines.items()}
        output = {}
        # The cache is scoped to one source/replacement; no matrix identities
        # or data-derived predictors are shared between hypotheses for free.
        self._cost_cache.clear()
        for model, description in self.baseline.items():
            delta = sum(
                self.block(model, view, pos, replacements) - description.blocks[view][pos]
                for view in self.views
                for pos in range(position, min(position + 4, self.count))
            )
            output[model] = description.bits + delta
        self._cost_cache.clear()
        return output


